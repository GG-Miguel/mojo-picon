"""Rebuild the guideline index in Qdrant from data/guides.json (RAG: Ingesta; idempotent).

    uv run python scripts/fetch_guides.py          # once: downloads the corpus
    uv run python scripts/ingest_rag.py --dry-run  # parse, transcribe and chunk; writes the report
    QDRANT_URL=... QDRANT_API_KEY=... uv run python scripts/ingest_rag.py

PDF pages are transcribed with Gemini once and cached next to the PDF (<id>.pages.json, git-ignored);
--retranscribe forces it again. The report (data/guides_report.md) lists the chunks per document
and the transcribed numbers that pypdf does not find on the same page, for manual review.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from fetch_guides import load_manifest, raw_path  # noqa: E402

from mojo_picon.config import Settings  # noqa: E402
from mojo_picon.rag.chunks import Chunk, chunk_document  # noqa: E402
from mojo_picon.rag.documents import Section, html_sections, jats_sections, page_sections  # noqa: E402
from mojo_picon.rag.transcribe import page_number_mismatches, page_texts, split_pages, transcribe_pages  # noqa: E402

REPORT = ROOT / "data" / "guides_report.md"


async def pdf_pages(guide: dict, settings: Settings, retranscribe: bool) -> list[str]:
    path = raw_path(guide)
    cache = path.with_suffix(".pages.json")
    if cache.exists() and not retranscribe:
        return json.loads(cache.read_text(encoding="utf-8"))
    from google import genai
    from google.genai import types

    client = genai.Client(
        vertexai=True,
        project=settings.gcp_project_id,
        location=settings.vertex_location,
        http_options=types.HttpOptions(base_url=settings.vertex_endpoint),
    )
    print(f"  transcribing {guide['id']} with {settings.gemini_model}…", flush=True)
    pages = await transcribe_pages(client, settings.gemini_model, split_pages(path.read_bytes()))
    cache.write_text(json.dumps(pages, ensure_ascii=False, indent=0), encoding="utf-8")
    return pages


async def sections_of(guide: dict, settings: Settings, retranscribe: bool) -> tuple[list[Section], dict[int, set]]:
    path = raw_path(guide)
    if guide["format"] == "html":
        return html_sections(path.read_text(encoding="utf-8")), {}
    if guide["format"] == "jats":
        return jats_sections(path.read_text(encoding="utf-8")), {}
    pages = await pdf_pages(guide, settings, retranscribe)
    extracted = page_texts(path.read_bytes())
    mismatches = {
        n: bad
        for n, (page, text) in enumerate(zip(pages, extracted, strict=True), start=1)
        if (bad := page_number_mismatches(page, text))
    }
    return page_sections(pages), mismatches


def write_report(rows: list[tuple[dict, list[Chunk], dict[int, set]]]) -> None:
    lines = [
        "# Guideline index report",
        "",
        "Generated by `scripts/ingest_rag.py`. Corpus: `data/guides.json`.",
        "",
        "| Document | Tag | Licence | Chunks | Characters |",
        "|---|---|---|---|---|",
    ]
    for guide, chunks, _ in rows:
        chars = sum(len(c.text) for c in chunks)
        lines.append(f"| {guide['title'][:70]} | {guide['tag']} | {guide['license']} | {len(chunks)} | {chars:,} |")
    lines += [
        "",
        "## Transcribed numbers not found by pypdf on the same page",
        "",
        "Review these pages by hand: a difference can be a transcription error, or pypdf missing text",
        "(numbers in images, split digits).",
        "",
    ]
    found = False
    for guide, _, mismatches in rows:
        for page, numbers in sorted(mismatches.items()):
            found = True
            lines.append(f"- {guide['tag']}, p. {page}: {', '.join(sorted(numbers)[:15])}")
    if not found:
        lines.append("None.")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="build the chunks and the report, no Qdrant")
    parser.add_argument("--retranscribe", action="store_true", help="transcribe the PDFs again")
    args = parser.parse_args()
    settings = Settings.from_env()
    logging.getLogger("pypdf").setLevel(logging.ERROR)  # font warnings that do not affect the text

    rows = []
    for guide in load_manifest():
        sections, mismatches = await sections_of(guide, settings, args.retranscribe)
        chunks = chunk_document(guide, sections)
        rows.append((guide, chunks, mismatches))
        print(f"{guide['id']:24} {len(sections):4} sections {len(chunks):4} chunks")
    write_report(rows)
    chunks = [c for _, cs, _ in rows for c in cs]
    print(f"{len(chunks)} chunks; report: {REPORT.relative_to(ROOT)}")
    if args.dry_run:
        return

    if not (settings.qdrant_url and settings.qdrant_api_key):
        sys.exit("QDRANT_URL and QDRANT_API_KEY are required (or use --dry-run)")
    from qdrant_client import AsyncQdrantClient

    from mojo_picon.llm import gemini_embeddings
    from mojo_picon.rag.index import GuideIndex

    embedder = gemini_embeddings(settings)
    dimension = len(await embedder.aembed_query("dimension"))
    client = AsyncQdrantClient(url=settings.qdrant_url, api_key=settings.qdrant_api_key, timeout=60)
    await GuideIndex(client, embedder).rebuild(chunks, dimension)
    print(f"indexed {len(chunks)} chunks in {settings.qdrant_url}")


if __name__ == "__main__":
    asyncio.run(main())
